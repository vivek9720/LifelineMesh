pub fn default_bank(bank: usize) -> Vec<PhraseRecord> {
    if PHRASES.is_empty() {
        return Vec::new();
    }
    let start = (bank * 16) % PHRASES.len();
    (0..16).map(|offset| PHRASES[(start + offset) % PHRASES.len()]).collect()
}

pub fn default_script_labels(id: usize) -> Vec<String> {
    let mut labels = Vec::new();
    for offset in 0..3 {
        let index = (id + offset) % PHRASES.len();
        labels.push(PHRASES[index].text.to_owned());
    }
    labels
}
